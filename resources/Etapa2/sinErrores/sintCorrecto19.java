class OperadoresBinarios {
    public void metodo() {
        int a = 10;
        int b = 5;
        boolean x = true;
        boolean y = false;
        
        // Operadores aritméticos
        int suma = a + b;
        int resta = a - b;
        int multiplicacion = a * b;
        int division = a / b;
        int modulo = a % b;
        
        // Operadores de comparación
        boolean igual = a == b;
        boolean diferente = a != b;
        boolean menor = a < b;
        boolean mayor = a > b;
        boolean menorIgual = a <= b;
        boolean mayorIgual = a >= b;
        
        // Operadores lógicos
        boolean and = x && y;
        boolean or = x || y;
    }
}
