class PrimitivosLiterales {
    public void metodo() {
        // Literales booleanos
        boolean verdadero = true;
        boolean falso = false;
        
        // Literales enteros
        int numero = 42;
        int negativo = -10;
        int cero = 0;
        
        // Literales de caracteres
        char letra = 'A';
        char numeroChar = '5';
        char especial = '\n';
        
        // Literal null
        String nulo = null;
        Object objeto = null;
    }
}
