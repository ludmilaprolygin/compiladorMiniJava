class SentenciasVacias {
    public void metodo() {
        // Sentencia vacía
        ;
        
        // Sentencia vacía en if
        if (true) {
            ;
        }
        
        // Sentencia vacía en else
        if (false) {
            int x = 10;
        } else {
            ;
        }
        
        // Sentencia vacía en while
        while (false) {
            ;
        }
        
        // Bloque vacío
        {
            ;
        }
    }
}
